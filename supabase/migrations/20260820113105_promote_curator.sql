-- ============================================================================
--  카공맵 — 첫 큐레이터 지정
-- ----------------------------------------------------------------------------
--  제보 화면이 생겼는데 큐레이터가 0명이면 승인 경로가 없다. approve_submission()
--  과 reject_submission()이 is_curator()로 먼저 막기 때문에, 지금 상태로는 누가
--  제보를 보내도 그것을 places로 옮길 사람이 없다.
--
--  role은 본인이 못 올린다 — profiles_update_own의 with check가 막는다. 그래서
--  이 승격은 마이그레이션(또는 service_role)으로만 가능하다. 그 제약을 푸는
--  대신 여기서 한 번 지정한다.
--
--  uuid를 하드코딩하는 것이 마음에 걸리지만, 대안은 "nickname으로 찾기"인데
--  그쪽은 동명이인이 생기는 순간 엉뚱한 사람을 올린다. 계정이 하나뿐인 지금
--  가장 좁게 겨냥하는 방법이 uuid다.
--
--  대상 행이 없는 환경(scripts/verify-schema.sh의 검증 컨테이너)에서는 0행
--  업데이트로 조용히 지나간다. 그래서 조건에 role까지 넣지 않았다.
-- ============================================================================

update public.profiles
   set role = 'curator'
 where id = '3e339f8f-cee8-45e7-a506-655079dad4dc';
