-- ============================================================================
--  카공맵 — 제보에 가게 이름을 받는다
-- ----------------------------------------------------------------------------
--  `place_reports`가 받는 것은 네이버 URL·사진·메모뿐이었다. 그래서 검수하는 사람은
--  **어느 가게인지 알려면 매번 링크를 열어야** 했고, 표에는 도메인(`naver.me`)만
--  줄줄이 찍혔다.
--
--  "URL에서 상호명을 자동으로 뽑으면 되지 않나"를 먼저 확인했고, **안 된다.**
--  `naver.me/XXXX`는 `map.naver.com/p/entry/place/<id>`로 307 리다이렉트하는데
--  그 주소에는 장소 ID만 있고 이름이 없다. 최종 페이지는 2.3KB짜리 JS 셸이라
--  `<title>`도 `og:title`도 비어 있다 — 이름은 클라이언트에서 렌더된다. 뽑으려면
--  헤드리스 브라우저를 띄워야 하는데 `map.naver.com/robots.txt`가 봇 접근을 막고,
--  무엇보다 **크롤링 금지**가 이 저장소의 구속력 있는 결정이다
--  (docs/mvp-decisions.md).
--
--  그래서 제보자에게 직접 받는다. 제보하는 사람은 이미 그 카페의 네이버 페이지를
--  보고 있으므로 아는 값이고, 긁어온 문자열보다 정확하다.
--
--  ⚠️ **필수가 아니다.** 이름을 몰라도 링크만으로 제보할 수 있어야 한다 —
--     이 칸을 required로 만들면 제보 문턱이 올라간다. 비면 검수하는 사람이 링크를
--     열어 확인하던 예전 흐름 그대로다.
--
--  `places.name`을 채우는 것은 여전히 큐레이터다. 이 값은 **제보자가 말한 이름**이지
--  확인된 상호가 아니므로, 승인 함수가 이것을 places로 옮기지 않는다. 관리자 폼이
--  기본값으로 깔아 주기만 하고 최종 판단은 사람이 한다.
-- ============================================================================

alter table public.place_reports
  add column place_name text
    check (
      place_name is null
      or (btrim(place_name) <> '' and char_length(place_name) <= 100)
    );

comment on column public.place_reports.place_name is
  '제보자가 적은 가게 이름. 선택 입력이고, 확인된 상호가 아니라 검수의 출발점이다.';
